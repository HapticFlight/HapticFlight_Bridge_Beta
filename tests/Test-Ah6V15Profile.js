const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const hook = fs.readFileSync(path.join(root, 'dcs-hook', 'DCSExtraTelemetry.lua'), 'utf8');
const profile = JSON.parse(fs.readFileSync(path.join(root, 'downloads', 'ah6-v1.5', 'DCS-AH-6J-Haptic-Engine-v2.0.0-AH6-v1.5-Rotor-Baseline.siprofile'), 'utf8'));
const rotor = profile.EffectsContainers.find(item => item.Description === 'Rotor and Powertrain');
const effect = name => rotor.EffectsContainers.find(item => item.Description === name);
const one = effect('AH-6 rotor 1-rev airframe pulse');
const two = effect('AH-6 rotor 2-rev structural harmonic');
assert(profile.Name.includes('v1.5 Rotor Baseline'));
assert(one.IsEnabled && one.Gain === 22, '1/rev must be a restrained normal default.');
assert(two.IsEnabled && two.Gain === 16, '2/rev must be a restrained normal default.');
assert(one.FrontLeftFrequencyFormula.Expression.includes('MainRotorHz'));
assert(two.FrontLeftFrequencyFormula.Expression.includes('MainRotorHz') && two.FrontLeftFrequencyFormula.Expression.includes('* 2'));
assert(hook.includes('LoGetAltitudeAboveGroundLevel'), 'AGL primary export fallback is missing.');
assert(hook.includes('LoGetAltitudeAboveGround'), 'AGL compatibility fallback is missing.');
assert(hook.includes('altitudeAglSource = altitudeAglSource'), 'AGL source is not recorded for validation.');
console.log('PASS: AH-6J v1.5 enables conservative phase-derived 1/rev and 2/rev rotor layers.');
